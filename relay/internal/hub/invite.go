package hub

import (
	"crypto/rand"
	"encoding/base64"
	"time"

	"github.com/scolomer/omp-xshell/relay/internal/proto"
)

// DefaultClaimTimeout is how long the holder of an offer has to grant or
// refuse a claim before the claimant is told error timeout. It leaves a human
// the time to confirm the request.
const DefaultClaimTimeout = 120 * time.Second

// MaxOffers is the number of invitations one connection may offer at once.
const MaxOffers = 16

// pendingClaim is a claim waiting for its holder. The relay never sees the
// invitation secret: invite_id is a derived identifier and the box it relays
// is opaque.
type pendingClaim struct {
	id       string // claim, generated by the relay
	claimant *Session
	frameID  string // id of the claimant's claim frame, echoed in the answer
	holder   *Session
	timer    *time.Timer
}

func (h *Hub) record(event string) {
	if h.rec != nil {
		h.rec.Invite(event)
	}
}

// Offer registers s as the holder of inviteID. Offering an invite_id s
// already holds is a no-op; one held by another connection, or a 17th offer,
// is refused with bad_frame.
func (h *Hub) Offer(s *Session, inviteID string) *Error {
	h.mu.Lock()
	defer h.mu.Unlock()
	if holder := h.offers[inviteID]; holder != nil {
		if holder == s {
			return nil
		}
		return &Error{proto.CodeBadFrame, "invite_id déjà proposé par une autre connexion"}
	}
	if len(s.offers) >= MaxOffers {
		return &Error{proto.CodeBadFrame, "trop d'invitations proposées par cette connexion"}
	}
	h.offers[inviteID] = s
	s.offers[inviteID] = struct{}{}
	if h.rec != nil {
		h.rec.OffersChanged(1)
	}
	return nil
}

// Withdraw removes s's own offer of inviteID; anything else is a no-op.
// Claims already forwarded to s stay pending: s may still answer them.
func (h *Hub) Withdraw(s *Session, inviteID string) {
	h.mu.Lock()
	defer h.mu.Unlock()
	if h.offers[inviteID] != s {
		return
	}
	delete(h.offers, inviteID)
	delete(s.offers, inviteID)
	if h.rec != nil {
		h.rec.OffersChanged(-1)
	}
}

// Claim forwards a claim_request, carrying the claimant's epk and req as
// received, to the holder of inviteID. The answer to the claimant (frame
// frameID) is sent later: granted, or error no_invite or timeout. An error is
// returned only when the claim cannot even be forwarded.
func (h *Hub) Claim(s *Session, frameID, inviteID, epk, req string) *Error {
	h.mu.Lock()
	defer h.mu.Unlock()
	h.record("claim")
	holder := h.offers[inviteID]
	if holder == nil {
		return noInvite()
	}
	pc := &pendingClaim{id: h.newClaimLocked(), claimant: s, frameID: frameID, holder: holder}
	if !h.Push(holder, proto.TypeClaimRequest, proto.ClaimRequest(inviteID, pc.id, epk, req)) {
		return noInvite()
	}
	h.claims[pc.id] = pc
	s.claims[pc.id] = pc
	holder.claims[pc.id] = pc
	pc.timer = time.AfterFunc(h.claimTimeout, func() { h.expire(pc) })
	return nil
}

// Grant relays box to the claimant of the claim addressed to s.
func (h *Hub) Grant(s *Session, claim, box string) *Error {
	h.mu.Lock()
	defer h.mu.Unlock()
	pc := h.claims[claim]
	if pc == nil || pc.holder != s {
		return noInvite()
	}
	h.dropClaimLocked(pc)
	h.record("grant")
	h.Push(pc.claimant, proto.TypeGranted, proto.Granted(pc.frameID, box))
	return nil
}

// RefuseClaim answers the claim addressed to s with error no_invite. A claim
// that no longer exists, or is not addressed to s, is ignored: the claimant
// was already answered or is gone.
func (h *Hub) RefuseClaim(s *Session, claim string) {
	h.mu.Lock()
	defer h.mu.Unlock()
	pc := h.claims[claim]
	if pc == nil || pc.holder != s {
		return
	}
	h.dropClaimLocked(pc)
	h.record("refuse")
	h.Refuse(pc.claimant, pc.frameID, noInvite())
}

// expire answers a claim whose holder stayed silent past the deadline.
func (h *Hub) expire(pc *pendingClaim) {
	h.mu.Lock()
	defer h.mu.Unlock()
	if h.claims[pc.id] != pc { // answered or dropped in the meantime
		return
	}
	h.dropClaimLocked(pc)
	h.record("timeout")
	pc.claimant.log.Info("invitation : le détenteur n'a pas répondu", "claim", pc.id)
	h.Refuse(pc.claimant, pc.frameID, &Error{proto.CodeTimeout, "le détenteur de l'invitation n'a pas répondu"})
}

// dropInvitesLocked forgets everything s offers or waits for. Claimants of a
// claim s was to answer get no_invite; claims s itself made are forgotten.
func (h *Hub) dropInvitesLocked(s *Session) {
	for inviteID := range s.offers {
		delete(h.offers, inviteID)
	}
	if n := len(s.offers); n > 0 && h.rec != nil {
		h.rec.OffersChanged(-n)
	}
	clear(s.offers)
	for _, pc := range s.claims {
		h.dropClaimLocked(pc)
		if pc.holder == s && pc.claimant != s {
			h.Refuse(pc.claimant, pc.frameID, noInvite())
		}
	}
}

func (h *Hub) dropClaimLocked(pc *pendingClaim) {
	pc.timer.Stop()
	delete(h.claims, pc.id)
	delete(pc.claimant.claims, pc.id)
	delete(pc.holder.claims, pc.id)
}

// newClaimLocked returns an unused random claim (128 bits, base64url).
func (h *Hub) newClaimLocked() string {
	for {
		var b [16]byte
		if _, err := rand.Read(b[:]); err != nil {
			// crypto/rand does not fail on supported platforms.
			panic("hub: random source unavailable: " + err.Error())
		}
		claim := base64.RawURLEncoding.EncodeToString(b[:])
		if _, taken := h.claims[claim]; !taken {
			return claim
		}
	}
}

func noInvite() *Error {
	return &Error{proto.CodeNoInvite, "invitation inconnue, expirée, refusée ou détenteur hors ligne"}
}
